/**
 * Format string replacing {0}, {1}, etc.
 */
export function t(key: string, lang: Language = 'en', ...args: (string | number)[]): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dict[key] || TRANSLATIONS.en[key] || key;
  if (args.length > 0) {
    text = text.replace(/\{(\d+)\}/g, (_, idx) => {
      const val = args[Number(idx)];
      return val !== undefined ? String(val) : '';
    });
  }
  return text;
}
